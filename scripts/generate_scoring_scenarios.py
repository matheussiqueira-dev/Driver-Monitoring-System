"""Generate shared/scoring-scenarios.json and shared/spatial-cases.json from the Python reference engine.

The Python EyeStateTracker + AttentionScorer (and is_phone_near_face) are the
reference implementation. This script replays fixed inputs through them and
stores the outputs, so the web (TypeScript) port can be tested for parity
against the same files.

Run after any intentional change to scoring rules:
    python scripts/generate_scoring_scenarios.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any, Dict, List

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from dms.scoring_scenarios import SCENARIOS, replay_scenario, replay_session  # noqa: E402
from dms.spatial_cases import build_cases  # noqa: E402

OUTPUT = ROOT / "shared" / "scoring-scenarios.json"
SPATIAL_OUTPUT = ROOT / "shared" / "spatial-cases.json"


def build_document() -> Dict[str, Any]:
    scenarios: List[Dict[str, Any]] = []
    for name, frames in SCENARIOS.items():
        scenarios.append(
            {
                "name": name,
                "frames": frames,
                "expected": replay_scenario(frames),
                "session": replay_session(frames),
            }
        )
    return {
        "description": "Generated by scripts/generate_scoring_scenarios.py from the Python reference scorer.",
        "scenarios": scenarios,
    }


def build_spatial_document() -> Dict[str, Any]:
    return {
        "description": "Generated by scripts/generate_scoring_scenarios.py from dms/spatial.py (phone near face).",
        "cases": build_cases(),
    }


def write_json(path: Path, document: Any) -> None:
    # newline="\n" keeps the file byte-identical on Windows and Linux (CI diffs it).
    path.write_text(json.dumps(document, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    print(f"Wrote {path.relative_to(ROOT)}")


def main() -> None:
    write_json(OUTPUT, build_document())
    write_json(SPATIAL_OUTPUT, build_spatial_document())


if __name__ == "__main__":
    main()
