"""Generate shared/scoring-scenarios.json from the Python reference scorer.

The Python EyeStateTracker + AttentionScorer are the reference implementation.
This script replays fixed input sequences through them and stores the outputs,
so the web (TypeScript) scorer can be tested for parity against the same file.

Run after any intentional change to scoring rules:
    python scripts/generate_scoring_scenarios.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any, Dict, List

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from dms.scoring_scenarios import SCENARIOS, replay_scenario  # noqa: E402

OUTPUT = ROOT / "shared" / "scoring-scenarios.json"


def build_document() -> Dict[str, Any]:
    scenarios: List[Dict[str, Any]] = []
    for name, frames in SCENARIOS.items():
        scenarios.append({"name": name, "frames": frames, "expected": replay_scenario(frames)})
    return {
        "description": "Generated by scripts/generate_scoring_scenarios.py from the Python reference scorer.",
        "scenarios": scenarios,
    }


def main() -> None:
    # newline="\n" keeps the file byte-identical on Windows and Linux (CI diffs it).
    content = json.dumps(build_document(), indent=2, ensure_ascii=False) + "\n"
    OUTPUT.write_text(content, encoding="utf-8", newline="\n")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
